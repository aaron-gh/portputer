// swift-tools-version: 6.0
// The Portputer Mac app. Build it with build.sh, which builds the Rust core
// first and generates the Swift bindings this package compiles against.

import Foundation
import PackageDescription

let repoRoot = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent().path
let rustLibDir = ProcessInfo.processInfo.environment["PORTPUTER_RUST_LIB_DIR"] ?? "\(repoRoot)/target/release"

let package = Package(
    name: "Portputer",
    platforms: [.macOS(.v14)],
    dependencies: [
        // Updates Portputer itself, as most Mac apps do: a separate process
        // downloads the new version, checks its signature, and offers to
        // install and relaunch.
        .package(url: "https://github.com/sparkle-project/Sparkle", from: "2.10.0"),
    ],
    targets: [
        // The C declarations of the Rust core's functions, generated by UniFFI.
        .target(name: "portputer_ffiFFI", path: "Sources/portputer_ffiFFI"),
        .executableTarget(
            name: "Portputer",
            dependencies: ["portputer_ffiFFI", .product(name: "Sparkle", package: "Sparkle")],
            path: "Sources/Portputer",
            swiftSettings: [.swiftLanguageMode(.v5)],
            linkerSettings: [
                .unsafeFlags(["-L", rustLibDir, "-Xlinker", "-rpath", "-Xlinker", "@executable_path/../Frameworks"]),
                .linkedLibrary("portputer_ffi"),
                .linkedLibrary("c++"),
                .linkedLibrary("iconv"),
                .linkedFramework("AppKit"),
                .linkedFramework("AudioToolbox"),
                .linkedFramework("CoreAudio"),
                .linkedFramework("IOKit"),
                .linkedFramework("ApplicationServices"),
                .linkedFramework("SystemConfiguration"),
                .linkedFramework("ServiceManagement"),
            ]
        ),
    ]
)
